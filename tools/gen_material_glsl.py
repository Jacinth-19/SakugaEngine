#!/usr/bin/env python3
"""Generates shaders/material_block.glsl from engine/gfx/MaterialProps.inc (keeps C++ and GLSL layouts in sync)."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
inc = "\n".join(l for l in (root / "engine/gfx/MaterialProps.inc").read_text().splitlines() if not l.strip().startswith("//"))
vec4 = re.findall(r"SK_MAT_VEC4\((\w+),", inc)
flt = re.findall(r"SK_MAT_FLOAT\((\w+),", inc)
n = len(flt)
pad = (-n) % 4
out = ["// GENERATED by tools/gen_material_glsl.py -- do not edit.",
       "layout(set = 1, binding = 0, std140) uniform MaterialUBO {"]
out += [f"    vec4 m_{v};" for v in vec4]
out += [f"    float m_{f};" for f in flt]
out += [f"    float m_pad{i};" for i in range(pad)]
out.append("} M;")
(root / "shaders/material_block.glsl").write_text("\n".join(out) + "\n")
print(f"{len(vec4)} vec4, {n} floats, {pad} pad")
